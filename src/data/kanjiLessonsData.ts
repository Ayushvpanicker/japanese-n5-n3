export function getKanjiByLesson(level: 'N5' | 'N4', lesson: number): KanjiLessonItem[] {
  return KANJI_LESSONS_DATA.filter(item => item.level === level && item.lesson === lesson);
}

export function getAvailableLessons(level: 'N5' | 'N4'): number[] {
  const lessons = new Set<number>();
  KANJI_LESSONS_DATA.filter(item => item.level === level).forEach(item => lessons.add(item.lesson));
  return Array.from(lessons).sort((a, b) => a - b);
}
